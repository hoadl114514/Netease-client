final List<int> _fp = List.generate(64, _ip.indexOf);

/// 从 [value]（[width] 位）里按 [positions]（从最高位数起）依次取位，拼成新数。
int _permute(int value, List<int> positions, int width) {
  var result = 0;
  for (final p in positions) {
    result = (result << 1) | ((value >> (width - 1 - p)) & 1);
  }
  return result;
}

/// 每个 32 位字按小端读写（对应上游的 BITNUM / InvIP）。
int _readBlock(List<int> b, int o) {
  var v = 0;
  for (final i in const [3, 2, 1, 0, 7, 6, 5, 4]) {
    v = (v << 8) | b[o + i];
  }
  return v;
}

void _writeBlock(int v, Uint8List out, int o) {
  const order = [3, 2, 1, 0, 7, 6, 5, 4];
  for (var k = 0; k < 8; k++) {
    out[o + order[k]] = (v >> (56 - 8 * k)) & 0xFF;
  }
}

List<int> _keySchedule(List<int> key, {required bool decrypt}) {
  final value = _readBlock(key, 0);
  var left = _permute(value, _pc1C, 64) << 4;
  var right = _permute(value, _pc1D, 64) << 4;
  final keys = <int>[];
  final pc2Right = [for (final p in _pc2.sublist(24)) p - 27]; // 上游就是 -27，不是笔误。
  for (final s in _shifts) {
    left = ((left << s) | (left >> (28 - s))) & 0xFFFFFFF0;
    right = ((right << s) | (right >> (28 - s))) & 0xFFFFFFF0;
    keys.add((_permute(left, _pc2.sublist(0, 24), 32) << 24) | _permute(right, pc2Right, 32));
  }
  return decrypt ? keys.reversed.toList() : keys;
}

final List<List<int>> _schedules = () {
  final k = latin1.encode(_key);
  return [
    _keySchedule(k.sublist(16), decrypt: true),
    _keySchedule(k.sublist(8, 16), decrypt: false),
    _keySchedule(k.sublist(0, 8), decrypt: true),
  ];
}();

int _cryptBlock(int block, List<int> keys) {
  final state = _permute(block, _ip, 64);
  var left = (state >>> 32) & 0xFFFFFFFF;
  var right = state & 0xFFFFFFFF;
  for (final key in keys) {
    final expanded = _permute(right, _expand, 32) ^ key;
    var value = 0;
    for (var i = 0; i < 8; i++) {
      final bits = (expanded >> (42 - 6 * i)) & 63;
      final index = (bits & 32) | ((bits & 31) >> 1) | ((bits & 1) << 4);
      value = (value << 4) | _sboxes[i][index];
    }
    final next = left ^ _permute(value, _p, 32);
    left = right;
    right = next;
  }
  return _permute((right << 32) | left, _fp, 64);
}

/// 解密 `lyric_download.fcg` 返回的十六进制密文，得到 QRC 的 XML（或纯文本）。
/// 密文不合法、解压失败时抛 [FormatException]。
String decryptQrc(String hex) {
  final clean = hex.replaceAll(RegExp(r'\s'), '');
  if (clean.isEmpty || clean.length % 16 != 0 || clean.length ~/ 2 > _maxBytes) {
    throw const FormatException('QRC 密文长度不合法');
  }
  if (!RegExp(r'^[0-9a-fA-F]+$').hasMatch(clean)) throw const FormatException('QRC 密文不是十六进制');
  final data = Uint8List(clean.length ~/ 2);
  for (var i = 0; i < data.length; i++) {
    data[i] = int.parse(clean.substring(i * 2, i * 2 + 2), radix: 16);
  }
  final out = Uint8List(data.length);
  for (var o = 0; o < data.length; o += 8) {
    var block = _readBlock(data, o);
    for (final keys in _schedules) {
      // 每轮输出按小端字写回，下一轮再按同样方式读入：两次转换互相抵消，直接传整数即可。
      block = _cryptBlock(block, keys);
    }
    _writeBlock(block, out, o);
  }
  final List<int> inflated;
  try {
    inflated = ZLibDecoder().convert(out);
  } catch (e) {
    throw FormatException('QRC 解压失败：$e');
  }
  if (inflated.length > _maxBytes) throw const FormatException('QRC 明文过大');
  var text = utf8.decode(inflated, allowMalformed: false);
  if (text.startsWith('﻿')) text = text.substring(1);
  return text.replaceFirst(RegExp(r'\u0000+$'), '');
}
